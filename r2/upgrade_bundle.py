def _interp(mcode, idx):
    wps = WAYPOINTS[mcode]
    if idx <= wps[0][0]:
        return list(wps[0][1]), wps[0][2]
    if idx >= wps[-1][0]:
        return list(wps[-1][1]), wps[-1][2]
    for i in range(len(wps) - 1):
        i0, p0, z0 = wps[i]
        i1, p1, z1 = wps[i + 1]
        if i0 <= idx <= i1:
            t = 0.0 if i1 == i0 else (idx - i0) / (i1 - i0)
            return [round(p0[k] + (p1[k] - p0[k]) * t, 4) for k in range(3)], (z0 if t < 0.5 else z1)
    return list(wps[-1][1]), wps[-1][2]

def run(bundle_path):
    p = Path(bundle_path)
    if not p.exists():
        return
    d = json.loads(p.read_text(encoding='utf-8'))
    for m in d.get('meridians', []):
        mid = m.get('code') or m.get('id') or ''
        flow = m.get('pathway') or m.get('flow') or ''
        m['code'] = mid
        m['pathway'] = flow
        if not m.get('indications'):
            m['indications'] = MERIDIAN_INDICATIONS.get(mid, '结合本经循行部位与所属脏腑辨证主治。')
    for g in d.get('glossary', []):
        txt = g.get('def') or g.get('desc') or g.get('definition') or ''
        g['def'] = txt
        g['desc'] = txt
    pts = []
    pos_map = {}
    for item in d.get('full_acupoints_catalog', []):
        code = item.get('code', '')
        mm = re.match(r'^([A-Z]+)(\d+)$', code)
        if mm and mm.group(1) in WAYPOINTS:
            pos, zone = _interp(mm.group(1), int(mm.group(2)))
            pos_map[code] = (zone, pos)
            pts.append({'code': code, 'name': item['name'], 'meridian': item['meridian'], 'pos': pos, 'zone': zone})
    if pts:
        d['points'] = pts
    det = d.get('acupoint_details', {})
    for item in d.get('full_acupoints_catalog', []):
        name = item['name']
        code = item['code']
        mer = item['meridian']
        cur = det.get(name, {})
        if name in KEY_ACUPOINT_CLINICAL:
            loc, ind, note = KEY_ACUPOINT_CLINICAL[name]
            det[name] = {'code': code, 'meridian': mer, 'type': '国标经穴', 'simple': f'{mer}（{code}），{loc}；主治{ind}。', 'detailed': f'【国标编码】GB/T 12346-2021 · {code}。【所属经脉】{mer}。【精准定位】{loc}。【主治病症】{ind}。【刺灸与安全提示】{note}'}
            continue
        if 'zone_' in (cur.get('simple', '') + cur.get('detailed', '')):
            z, pos = pos_map.get(code, ('torso_front', [0, 1.0, 0]))
            zzh, note = ZONE_ZH.get(z, ('体表循行区', '配合骨度分寸法定位。'))
            det[name] = {
                'code': code, 'meridian': mer, 'type': '国标经穴',
                'simple': f'{mer}（{code}），位于{zzh}循行线上，主治本经所属脏腑及局部病证。',
                'detailed': f'【国标编码】GB/T 12346-2021 · {code}。【所属经脉】{mer}。【分区定位】{zzh}体表及肌筋膜解剖层。【刺灸提示】{note}',
            }
    p.write_text(json.dumps(d, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
    print(f'[ok] Upgraded {p}: {len(pts)} 3D acupoints, {len(det)} details')
