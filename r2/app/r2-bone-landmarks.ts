export function getChineseAnatomyExplanation(rawName: string, systemId: string): string {
  for (const item of BONE_LANDMARK_DB) {
    if (item.re.test(rawName)) {
      return `${item.guide.overview}\n【核心骨性标志（沟/棘/嵴/突/窝/孔）】\n· ${item.guide.landmarks.join('\n· ')}`;
    }
  }
  const key = (systemId || '').toLowerCase();
  return SYSTEM_ZH_DESC[key] || '人体标准解剖结构，可结合孤立观察与三维爆炸分解查看其邻近血管、神经与骨性标志关系。';
}
